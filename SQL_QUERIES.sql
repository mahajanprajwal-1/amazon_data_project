/*
6. Least-Selling Categories by State
Identify the least-selling product category for each state.
Challenge: Include the total sales for that category within each state.
*/

WITH ranking_table AS (
    SELECT
        c.state,
        cat.category_name,
        SUM(oi.total_price) AS total_sale,
        RANK() OVER (PARTITION BY c.state ORDER BY SUM(oi.total_price) ASC) AS rnk
    FROM orders AS o
    JOIN customers AS c    ON o.customer_id  = c.customer_id
    JOIN order_items AS oi ON o.order_id     = oi.order_id
    JOIN products AS p     ON p.product_id   = oi.product_id
    JOIN category AS cat   ON cat.category_id = p.category_id
    GROUP BY 1, 2
)
SELECT *
FROM ranking_table
WHERE rnk = 1
ORDER BY state;

/*
7. Customer Lifetime Value (CLTV)
Calculate the total value of orders placed by each customer over their lifetime.
Challenge: Rank customers based on their CLTV.
*/

SELECT 
c.customer_id,
CONCAT(c.f_name,' ',c.l_name) as full_name,
COUNT(DISTINCT oi.order_id) as No_of_orders,
SUM(oi.total_price) as total_value,
RANK() OVER( ORDER BY SUM(oi.total_price) DESC )as cltv_rank
FROM customers as c
JOIN orders as o
ON c.customer_id = o.customer_id
JOIN order_items as oi
ON oi.order_id = o.order_id
GROUP BY 1 , 2
ORDER BY cltv_rank;


