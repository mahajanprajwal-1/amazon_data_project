/*
1. TOP selling Products
Query the top 10 products by total sales value.
Challenge : Include product name , total quantity sold and total sales vlaue
*/


SELECT 
p.product_id,
p.product_name,
SUM(quantity) as total_quantity_sold,
SUM(total_price) as total_amount,
RANK() OVER(ORDER BY SUM(total_price) DESC) as rnk
FROM order_items as oi
LEFT JOIN products as p
ON p.product_id = oi.product_id
GROUP BY 1, 2
LIMIT 10;


/*
2. Revenue by Category
Calculate total revenue generated by each product Category.
Challenge : Include the percentage Contibution of each category to total revenue
*/

SELECT
    c.category_id,
    c.category_name,
    SUM(oi.total_price) AS category_revenue,
    ROUND(
        SUM(oi.total_price) * 100.0 / SUM(SUM(oi.total_price)) OVER (),
    2) AS percentage_contri
FROM order_items oi
JOIN products p ON p.product_id = oi.product_id
JOIN category c ON c.category_id = p.category_id
GROUP BY 1, 2;


/*
3. Average Order Value (AOV)
Compute the average order value for each customer
Challange : Include only customers with more than 5 orders 
*/

SELECT 
  c.customer_id,
  CONCAT(c.f_name, ' ', c.l_name) as full_name,
  SUM(total_price)/ COUNT(o.order_id) as AOV,
  COUNT(o.order_id) as total_orders 
FROM orders as o
JOIN customers as c
ON c.customer_id = o.customer_id
JOIN order_items as oi
ON oi.order_id = o.order_id
GROUP BY 1
HAVING  COUNT(o.order_id) > 25


/*
4. Monthly Sales Trend
Query monthly total sales over the past year.
Challenge: Display the sales trend, grouping by month, return current_month sale, last month sale!
*/

SELECT 
   Year,
   month,
   total_sale as current_month_sale,
   LAG(total_sale, 1) OVER(ORDER BY year, month) as last_month_sale
FROM 
(
SELECT
 EXTRACT(MONTH FROM o.order_date) as month,
 EXTRACT(YEAR FROM o.order_date) as Year,
 SUM(oi.total_price) as total_sale
FROM order_items as oi
JOIN orders as o 
ON o.order_id = oi.order_id
WHERE order_date >= CURRENT_DATE - INTERVAL '1 year'
GROUP BY 1 , 2
ORDER BY 2 ,1
) as t1



